'use client';

import { useEffect, useState, useRef } from 'react';
import { api } from '@/lib/api';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { Badge } from '@/components/ui/badge';
import { Skeleton } from '@/components/ui/skeleton';
import { AlertCircle, Activity } from 'lucide-react';

export default function AlertsPage() {
  const [events, setEvents] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [wsStatus, setWsStatus] = useState<'Connecting' | 'Connected' | 'Disconnected'>('Connecting');
  
  const wsRef = useRef<WebSocket | null>(null);

  useEffect(() => {
    // 1. Fetch initial events
    async function fetchInitialEvents() {
      try {
        const response = await api.get('/api/events/?limit=100');
        setEvents(response.data);
      } catch (err) {
        setError('Failed to load initial event log.');
      } finally {
        setLoading(false);
      }
    }
    fetchInitialEvents();

    // 2. Connect WebSocket
    // Note: The FastAPI backend currently does not enforce authentication on this WebSocket route
    const wsUrl = process.env.NEXT_PUBLIC_API_URL?.replace('http', 'ws') || 'ws://localhost:8000';
    const ws = new WebSocket(`${wsUrl}/api/ws/alerts`);
    wsRef.current = ws;

    ws.onopen = () => setWsStatus('Connected');
    ws.onclose = () => setWsStatus('Disconnected');
    ws.onmessage = (event) => {
      try {
        const newEvent = JSON.parse(event.data);
        setEvents((prev) => [newEvent, ...prev].slice(0, 100)); // Keep top 100
      } catch (e) {
        console.error('Failed to parse websocket message', e);
      }
    };

    return () => {
      ws.close();
    };
  }, []);

  const getConfidenceBadge = (confidence: number) => {
    if (confidence >= 0.85) return <Badge variant="destructive">High</Badge>;
    if (confidence >= 0.70) return <Badge className="bg-amber-500 hover:bg-amber-600">Medium</Badge>;
    return <Badge className="bg-emerald-500 hover:bg-emerald-600">Low</Badge>;
  };

  const getAlertCard = (event: any) => {
    const isHigh = event.confidence >= 0.85;
    const isMedium = event.confidence >= 0.70 && event.confidence < 0.85;
    
    return (
      <Card key={event.id} className="bg-zinc-900 border-zinc-800 text-white mb-4">
        <CardContent className="p-4 flex items-center justify-between gap-4">
          <div className="flex flex-col gap-1 w-24 flex-shrink-0">
            {isHigh && <Badge variant="destructive" className="w-fit">🔴 HIGH</Badge>}
            {isMedium && <Badge className="bg-amber-500 hover:bg-amber-600 text-white w-fit">🟠 MEDIUM</Badge>}
            {!isHigh && !isMedium && <Badge className="bg-emerald-500 hover:bg-emerald-600 w-fit">🟡 LOW</Badge>}
          </div>
          <div className="flex-1 flex flex-col">
            <h4 className="font-bold text-lg">Student {event.student_id || 'Unknown'}</h4>
            <span className="capitalize text-zinc-300 font-medium">{event.behaviour_type.replace(/_/g, ' ')}</span>
            <span className="text-sm text-zinc-400 mt-1">
              <strong>Explanation:</strong> {event.explanation}
            </span>
            <span className="text-xs text-zinc-500 mt-1">Time: {new Date(event.timestamp).toLocaleString()}</span>
          </div>
          <div className="flex flex-col items-center justify-center p-3 border border-zinc-800 rounded-md bg-zinc-950">
            <span className="text-xs text-zinc-500 uppercase font-semibold">Confidence</span>
            <span className="text-xl font-bold">{(event.confidence * 100).toFixed(0)}%</span>
          </div>
        </CardContent>
      </Card>
    );
  };

  const recentEvents = events.slice(0, 10); // Display top 10 as cards

  return (
    <div className="space-y-6">
      <div className="flex justify-between items-end">
        <div>
          <h2 className="text-3xl font-bold tracking-tight">Active Alerts</h2>
          <p className="text-zinc-400 mt-2">Explainable behavioural alerts generated by DRISHTI AI</p>
        </div>
        <div className="flex items-center gap-2">
          <span className="text-sm text-zinc-400">Live Feed:</span>
          {wsStatus === 'Connected' ? (
            <Badge className="bg-emerald-500 hover:bg-emerald-600 flex items-center gap-1">
              <Activity className="h-3 w-3" /> Connected
            </Badge>
          ) : (
            <Badge variant="destructive" className="flex items-center gap-1">
              <AlertCircle className="h-3 w-3" /> {wsStatus}
            </Badge>
          )}
        </div>
      </div>

      {error && <div className="text-red-500">{error}</div>}

      <div className="grid gap-6 xl:grid-cols-2">
        <div>
          <h3 className="text-xl font-semibold mb-4">Recent Alerts</h3>
          {loading ? (
            <div className="space-y-4">
              <Skeleton className="h-32 w-full bg-zinc-900 rounded-xl" />
              <Skeleton className="h-32 w-full bg-zinc-900 rounded-xl" />
            </div>
          ) : recentEvents.length === 0 ? (
            <div className="text-zinc-500 text-center py-8 bg-zinc-900/50 rounded-xl border border-zinc-800/50">
              No alerts detected.
            </div>
          ) : (
            <div>
              {recentEvents.map(getAlertCard)}
            </div>
          )}
        </div>

        <div>
          <Card className="bg-zinc-900 border-zinc-800 text-white sticky top-6">
            <CardHeader>
              <CardTitle>Event Timeline</CardTitle>
              <CardDescription className="text-zinc-400">Chronological list of recent detections</CardDescription>
            </CardHeader>
            <CardContent>
              <div className="rounded-md border border-zinc-800 h-[600px] overflow-auto">
                <Table>
                  <TableHeader className="bg-zinc-950 sticky top-0 z-10">
                    <TableRow className="border-zinc-800">
                      <TableHead className="text-zinc-400">Time</TableHead>
                      <TableHead className="text-zinc-400">Student</TableHead>
                      <TableHead className="text-zinc-400">Severity</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {loading ? (
                       <TableRow className="border-zinc-800">
                         <TableCell colSpan={3} className="text-center py-4"><Skeleton className="h-4 w-full bg-zinc-800"/></TableCell>
                       </TableRow>
                    ) : events.length === 0 ? (
                      <TableRow>
                        <TableCell colSpan={3} className="h-24 text-center text-zinc-500">
                          No events in timeline.
                        </TableCell>
                      </TableRow>
                    ) : (
                      events.map((event) => (
                        <TableRow key={event.id} className="border-zinc-800">
                          <TableCell className="font-mono text-xs">
                            {new Date(event.timestamp).toLocaleTimeString()}
                          </TableCell>
                          <TableCell>{event.student_id || 'Unknown'}</TableCell>
                          <TableCell>{getConfidenceBadge(event.confidence)}</TableCell>
                        </TableRow>
                      ))
                    )}
                  </TableBody>
                </Table>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
}
