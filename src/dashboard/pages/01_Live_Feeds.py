import json
from pathlib import Path

import pandas as pd
import streamlit as st


st.set_page_config(
    page_title="DRISHTI AI - Active Alerts",
    page_icon="🚨",
    layout="wide",
)


LOG_PATH = Path("logs/events.json")


# --------------------------------------------------
# Load events
# --------------------------------------------------

def load_events():

    if not LOG_PATH.exists():
        return []

    try:
        return json.loads(
            LOG_PATH.read_text(
                encoding="utf-8"
            )
        )

    except (json.JSONDecodeError, OSError):
        return []


events = load_events()


# --------------------------------------------------
# Alert severity
# --------------------------------------------------

def get_alert_level(confidence):

    confidence = float(confidence)

    if confidence >= 0.85:
        return "HIGH"

    if confidence >= 0.70:
        return "MEDIUM"

    return "LOW"


# --------------------------------------------------
# Page header
# --------------------------------------------------

st.title("🚨 Active Alerts")

st.caption(
    "Explainable behavioural alerts generated by DRISHTI AI"
)


# --------------------------------------------------
# Summary metrics
# --------------------------------------------------

high_alerts = 0
medium_alerts = 0
low_alerts = 0

for event in events:

    level = get_alert_level(
        event.get("confidence", 0)
    )

    if level == "HIGH":
        high_alerts += 1

    elif level == "MEDIUM":
        medium_alerts += 1

    else:
        low_alerts += 1


col1, col2, col3, col4 = st.columns(4)

col1.metric(
    "Total Alerts",
    len(events)
)

col2.metric(
    "High",
    high_alerts
)

col3.metric(
    "Medium",
    medium_alerts
)

col4.metric(
    "Low",
    low_alerts
)


st.divider()


# --------------------------------------------------
# Active alerts
# --------------------------------------------------

st.subheader("Recent Alerts")


if events:

    recent_events = list(
        reversed(events[-100:])
    )

    for event in recent_events:

        confidence = float(
            event.get("confidence", 0)
        )

        level = get_alert_level(
            confidence
        )

        student = event.get(
            "student_id",
            "Unknown"
        )

        behaviour = event.get(
            "behaviour_type",
            "Unknown behaviour"
        )

        explanation = event.get(
            "explanation",
            "No explanation available."
        )

        timestamp = event.get(
            "timestamp",
            "Unknown"
        )


        # ------------------------------------------
        # Alert card
        # ------------------------------------------

        with st.container(border=True):

            col1, col2, col3 = st.columns(
                [1, 4, 1]
            )

            with col1:

                if level == "HIGH":
                    st.error(
                        f"🔴 {level}"
                    )

                elif level == "MEDIUM":
                    st.warning(
                        f"🟠 {level}"
                    )

                else:
                    st.info(
                        f"🟡 {level}"
                    )


            with col2:

                st.markdown(
                    f"### Student {student}"
                )

                st.write(
                    behaviour
                    .replace("_", " ")
                    .title()
                )

                st.write(
                    f"**Explanation:** "
                    f"{explanation}"
                )

                st.caption(
                    f"Time: {timestamp}"
                )


            with col3:

                st.metric(
                    "Confidence",
                    f"{confidence:.0%}"
                )


else:

    st.success(
        "No alerts detected."
    )


# --------------------------------------------------
# Event timeline
# --------------------------------------------------

st.divider()

st.subheader("Event Timeline")


if events:

    rows = []

    for event in recent_events:

        confidence = float(
            event.get("confidence", 0)
        )

        rows.append(
            {
                "Severity": get_alert_level(
                    confidence
                ),
                "Timestamp": event.get(
                    "timestamp"
                ),
                "Student": event.get(
                    "student_id"
                ),
                "Behaviour": event.get(
                    "behaviour_type"
                ),
                "Confidence": f"{confidence:.0%}",
                "Explanation": event.get(
                    "explanation"
                ),
            }
        )

    st.dataframe(
        pd.DataFrame(rows),
        use_container_width=True,
        hide_index=True,
    )


# --------------------------------------------------
# Student summary
# --------------------------------------------------

st.divider()

st.subheader("Alerts by Student")


if events:

    student_counts = {}

    for event in events:

        student = event.get(
            "student_id"
        )

        if student:

            student_counts[student] = (
                student_counts.get(
                    student,
                    0
                ) + 1
            )


    summary_rows = [
        {
            "Student": student,
            "Alert Count": count,
        }

        for student, count
        in sorted(
            student_counts.items(),
            key=lambda x: x[1],
            reverse=True,
        )
    ]


    st.dataframe(
        pd.DataFrame(summary_rows),
        use_container_width=True,
        hide_index=True,
    )

else:

    st.info(
        "No student alerts available."
    )


# --------------------------------------------------
# Refresh
# --------------------------------------------------

st.divider()

if st.button(
    "🔄 Refresh Alerts"
):

    st.rerun()