from dataclasses import dataclass, field
from typing import List, Optional, Dict, Any


@dataclass
class StudentState:
    """
    Current anonymised state of one tracked student.
    """

    student_id: str

    bbox: List[float]

    keypoints: List[List[float]] = field(default_factory=list)

    track_confidence: float = 0.0

    frame_number: int = 0

    timestamp: Optional[float] = None

    features: Dict[str, Any] = field(default_factory=dict)


@dataclass
class BehaviourEvent:
    """
    A behavioural observation generated by the behaviour engine.

    This is an observation/alert, NOT a definitive cheating verdict.
    """

    student_id: str

    behaviour_type: str

    confidence: float

    explanation: str

    timestamp: Optional[float] = None

    frame_number: Optional[int] = None

    evidence: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ObjectDetection:
    """
    Detected object associated with a frame/student.
    """

    object_type: str

    confidence: float

    bbox: List[float]

    student_id: Optional[str] = None